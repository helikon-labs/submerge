import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';

function headerifyTopCategories(items: [any]) {
    return items.map((item) => {
        if (item.type === 'category') {
            // remove link & collapse behaviour
            const { link, ...rest } = item;
            return {
                ...rest,
                collapsible: false,
                collapsed: false, // has no effect if collapsible is false
                items: headerifyTopCategories(item.items),
            };
        }
        return item;
    });
}

const placeholderAPISidebar = require('./docs/placeholder-api/sidebar.js');

const sidebars: SidebarsConfig = {
    tutorialSidebar: [
        {
            type: 'doc',
            id: 'introduction',
            label: 'Introduction',
        },
        {
            type: 'category',
            label: 'Basics',
            collapsible: false,
            items: [
                {
                    type: 'autogenerated',
                    dirName: 'tutorial-basics',
                },
            ],
        },
        {
            type: 'category',
            label: 'Extras',
            collapsible: false,
            items: [
                {
                    type: 'autogenerated',
                    dirName: 'tutorial-extras',
                },
            ],
        },
    ],
    placeholderAPISidebar: headerifyTopCategories(placeholderAPISidebar),
};

export default sidebars;
